export const loadSqliteBenchDatabase = async () => {
  try {
    const { default: Database } = await import('better-sqlite3');
    return Database;
  } catch (err) {
    console.error(`better-sqlite3 missing: ${err?.message || err}`);
    process.exit(1);
  }
};

export const createSqliteBenchWorkspace = async ({ name, sqliteMode = 'code' }) => {
  const tempRoot = resolveDevelopmentArtifactPath(process.cwd(), 'bench-cache', name);
  await fs.mkdir(tempRoot, { recursive: true });
  const createOwned = async prefix => {
    const invocationRoot = await fs.mkdtemp(path.join(tempRoot, prefix));
    const workOwner = await createSqliteArtifactWorkOwner({ parentRoot: tempRoot, runRoot: invocationRoot });
    return { tempRoot: invocationRoot, workRoot: workOwner.workRoot, workOwner };
  };
  const owned = await createOwned('run-'), { tempRoot: invocationRoot, workOwner } = owned;
  const bundleDir = path.join(workOwner.workRoot, 'bundles');
  await fs.mkdir(bundleDir, { recursive: true });
  return {
    tempRoot: invocationRoot,
    workRoot: workOwner.workRoot,
    workOwner,
    createArmWorkspace: () => createOwned('arm-'),
    bundleDir,
    outPathBaseline: path.join(workOwner.workRoot, `index-${sqliteMode}-baseline.db`),
    outPathCurrent: path.join(workOwner.workRoot, `index-${sqliteMode}-current.db`)
  };
};

export const resolveSqliteBenchChunkKind = (sqliteMode) => {
  if (sqliteMode === 'records') return 'Record';
  return sqliteMode === 'code' ? 'code' : 'prose';
};

export const createSqliteBenchChunks = ({ file, suffix, chunksPerFile, kind, tokensPerChunk = 2, vocabularySize = 4096 }) => {
  const chunks = [];
  let offset = 0;
  for (let i = 0; i < chunksPerFile; i += 1) {
    const name = `fn${suffix}-${i}`, tokens = [`tok-${suffix}`, `tok-${i}`];
    const seed = createHash('sha256').update(`${suffix}:${i}`).digest().readUInt32LE(0);
    for (let token = 2; token < tokensPerChunk; token++) {
      tokens.push(token % 4 === 0 ? 'shared-term' : `vocab-${(seed + token * 31) % vocabularySize}`);
    }
    const line = `${name} ${tokens.join(' ')}`;
    chunks.push({
      file,
      start: offset,
      end: offset + line.length,
      startLine: i + 1,
      endLine: i + 1,
      kind,
      name,
      tokens
    });
    offset += line.length + 1;
  }
  return chunks;
};

/** Synthetic lexical fixture, published by the same immutable snapshot owner as
 * production. Source hash/size bind the actual generated bytes, not fake labels. */
export const publishSqliteBenchSource = async ({ bundleDir, file, chunks, mtimeMs }) => {
  const source = chunks.map(chunk => `${chunk.name} ${chunk.tokens.join(' ')}`).join('\n') + '\n';
  const entry = { hash: createHash('sha256').update(source).digest('hex'),
    size: Buffer.byteLength(source), mtimeMs, dependencySignatures: {} };
  const snapshot = await writeIncrementalBundleSnapshot({ bundleDir, relKey: file, entry,
    bundles: [{ file, hash: entry.hash, size: entry.size, dependencySignatures: entry.dependencySignatures, chunks }], format: 'json' });
  // Snapshot publication returns xxh64 for a new write and its admitted
  // canonical SHA256 identity for an existing immutable shard. Benchmark
  // cohorts use that same supported canonical identity in both cases, so
  // prior fixture publication cannot change an otherwise identical manifest.
  return { ...entry, ...snapshot, bundleChecksum: 'sha256:' + snapshot.bundleInventory[0].hash };
};

export const createSqliteBenchBundleFixture = async ({
  bundleDir,
  fileCount,
  chunksPerFile,
  sqliteMode = 'code',
  tokensPerChunk = 2,
  vocabularySize = 4096
}) => {
  const manifest = { artifactSurfaceVersion: ARTIFACT_SURFACE_VERSION, files: {} };
  if (sqliteMode === 'records') {
    setRecordsIncrementalCapability(manifest, true);
  }
  const chunkKind = resolveSqliteBenchChunkKind(sqliteMode);
  const buildChunks = (file, suffix, count = chunksPerFile) => createSqliteBenchChunks({
    file,
    suffix,
    chunksPerFile: count,
    kind: chunkKind,
    tokensPerChunk,
    vocabularySize
  });

  for (let i = 0; i < fileCount; i += 1) {
    const file = `src/file-${i}.js`;
    manifest.files[file] = await publishSqliteBenchSource({ bundleDir, file,
      chunks: buildChunks(file, `v1-${i}`), mtimeMs: 1000 + i });
  }

  return { manifest, buildChunks };
};

export const resolveSqliteBenchSize = (value, fallback) => {
  if (value === undefined) return fallback;
  const number = typeof value === 'string' && value.trim() ? Number(value) : NaN;
  if (!Number.isSafeInteger(number) || number <= 0) throw new TypeError('SQLite benchmark sizes must be positive safe integers.');
  return number;
};

export const requireSqliteDb = (dbPath, message = 'Expected sqlite DB to be created.') => {
  if (!fsSync.existsSync(dbPath)) {
    console.error(message);
    process.exit(1);
  }
};
