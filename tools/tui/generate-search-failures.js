#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createCli } from '../../src/shared/cli.js';
import { TUI_OPERATION_FAILURES as catalog } from '../../src/contracts/tui-operation-failures.js';

const root = fileURLToPath(new URL('../../', import.meta.url));
const args = createCli({ scriptName: 'generate-search-failures', options: { out: { type: 'string' } } })
  .strictOptions().parse();
const quote = JSON.stringify;
const rows = Object.entries(catalog.reasons).map(([reason, value]) =>
  `        ${quote(reason)} => Some(FailureDefinition { reason: ${quote(reason)}, outcome: ${quote(value.outcome)}, message: ${quote(value.message)}, actions: &[${value.actions.map(quote).join(', ')}] }),`);
const codeRows = Object.entries(catalog.codes).map(([code, reason]) => `        ${quote(code)} => ${quote(reason)},`);
const body = `// Generated by tools/tui/generate-search-failures.js; edit src/contracts/tui-operation-failures.json.
#[derive(Clone, Copy, Debug)]
pub(crate) struct FailureDefinition {
    pub reason: &'static str,
    pub outcome: &'static str,
    pub message: &'static str,
    pub actions: &'static [&'static str],
}
pub(crate) const VERSION: u64 = ${catalog.version};
pub(crate) const FIELDS: &[&str] = &[${catalog.fields.map(quote).join(', ')}];
pub(crate) fn definition(reason: &str) -> Option<FailureDefinition> {
    match reason {
${rows.join('\n')}
        _ => None,
    }
}
pub(crate) fn reason_for_code(code: &str) -> &'static str {
    match code {
${codeRows.join('\n')}
        _ => "unknown",
    }
}
`;
const output = args.out || path.join(root, 'crates/pairofcleats-tui/src/search_failure_catalog.rs');
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, body);
