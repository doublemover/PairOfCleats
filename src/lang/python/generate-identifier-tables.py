"""Regenerate the checked-in CPython identifier profile; never used at runtime."""
import json
import argparse
import pathlib
import sys
import unicodedata

root = pathlib.Path(__file__).resolve().parents[3]
pin = (root / '.python-version').read_text(encoding='utf-8').strip()
pinned_version = tuple(int(part) for part in pin.split('.'))
if (sys.implementation.name != 'cpython' or sys.version_info[:3] != pinned_version
        or pinned_version[:2] != (3, 15) or unicodedata.unidata_version != '17.0.0'):
    raise RuntimeError('Repository-pinned CPython ' + pin + ' / Unicode 17.0.0 required')
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--out', type=pathlib.Path, default=pathlib.Path(__file__).with_name('identifier-tables.js'))
args = parser.parse_args()

def ranges(predicate):
    result = []
    for value in range(0x110000):
        if predicate(chr(value)):
            if result and result[-1][1] == value - 1:
                result[-1][1] = value
            else:
                result.append([value, value])
    return result

output = ['// Generated by generate-identifier-tables.py using pinned CPython ' + pin + ' / UCD 17.0.0.',
          '// Exact isidentifier predicates exclude join controls accepted by Unicode ID_Continue.']
for name, predicate in [('PYTHON_XID_START', lambda char: char.isidentifier()),
                        ('PYTHON_XID_CONTINUE', lambda char: ('a' + char).isidentifier())]:
    entries = ranges(predicate)
    output.append('export const ' + name + ' = Object.freeze([')
    for offset in range(0, len(entries), 8):
        output.append('  ' + ','.join(json.dumps(row, separators=(',', ':')) for row in entries[offset:offset + 8]) + ',')
    output.append('].map(Object.freeze));')
args.out.write_text('\n'.join(output) + '\n', encoding='utf-8')
