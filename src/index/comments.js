const COMMENT_REGEX_CONFIG = { flags: 'i' };

const compilePattern = (value, fallback) => {
  if (value === null || value === undefined) return fallback;
  if (value === fallback) return fallback;
  if (isSafeRegex(value)) {
    return createSafeRegex(value.source, value.flags, { ...value.config, engine: value.engine }) || fallback;
  }
  if (value instanceof RegExp) {
    return createSafeRegex(value.source, value.flags, COMMENT_REGEX_CONFIG) || fallback;
  }
  if (typeof value === 'string' && value.trim()) {
    return createSafeRegex(value, 'i', COMMENT_REGEX_CONFIG) || fallback;
  }
  return fallback;
};

const DEFAULT_LICENSE_PATTERN = createSafeRegex(DEFAULT_COMMENT_CONFIG.licensePattern, 'i', COMMENT_REGEX_CONFIG);
const DEFAULT_GENERATED_PATTERN = createSafeRegex(DEFAULT_COMMENT_CONFIG.generatedPattern, 'i', COMMENT_REGEX_CONFIG);
const DEFAULT_LINTER_PATTERN = createSafeRegex(DEFAULT_COMMENT_CONFIG.linterPattern, 'i', COMMENT_REGEX_CONFIG);

export function normalizeCommentConfig(input = {}) {
  const cfg = input && typeof input === 'object' ? input : {};
  const extractRaw = typeof cfg.extract === 'string' ? cfg.extract.toLowerCase() : '';
  const extract = ['off', 'doc', 'all'].includes(extractRaw) ? extractRaw : DEFAULT_COMMENT_CONFIG.extract;
  return {
    extract,
    includeInCode: cfg.includeInCode === true,
    includeLicense: cfg.includeLicense === true,
    minDocChars: normalizeLimit(cfg.minDocChars, DEFAULT_COMMENT_CONFIG.minDocChars),
    minInlineChars: normalizeLimit(cfg.minInlineChars, DEFAULT_COMMENT_CONFIG.minInlineChars),
    minTokens: normalizeLimit(cfg.minTokens, DEFAULT_COMMENT_CONFIG.minTokens),
    maxPerChunk: normalizeLimit(cfg.maxPerChunk, DEFAULT_COMMENT_CONFIG.maxPerChunk),
    maxBytesPerChunk: normalizeLimit(cfg.maxBytesPerChunk, DEFAULT_COMMENT_CONFIG.maxBytesPerChunk),
    headerMaxLines: normalizeLimit(cfg.headerMaxLines, DEFAULT_COMMENT_CONFIG.headerMaxLines),
    licensePattern: compilePattern(cfg.licensePattern, DEFAULT_LICENSE_PATTERN),
    generatedPattern: compilePattern(cfg.generatedPattern, DEFAULT_GENERATED_PATTERN),
    linterPattern: compilePattern(cfg.linterPattern, DEFAULT_LINTER_PATTERN),
    skipGenerated: cfg.skipGenerated !== false,
    skipLinter: cfg.skipLinter !== false
  };
}

const resolveCommentStyle = ({ ext, languageId }) => {
  const resolvedId = languageId || (ext && EXT_OVERRIDES.get(ext)) || null;
  if (!resolvedId) return null;
  const match = COMMENT_STYLES.find((entry) => entry.ids.has(resolvedId));
  return match || null;
};

const splitLinesWithOffsets = (raw, baseOffset) => {
  const lines = [];
  let start = 0;
  for (let i = 0; i < raw.length; i += 1) {
    if (raw[i] === '\n') {
      lines.push({ raw: raw.slice(start, i), offset: baseOffset + start });
      start = i + 1;
    }
  }
  lines.push({ raw: raw.slice(start), offset: baseOffset + start });
  return lines;
};

const stripLineComment = (line, marker) => {
  let value = line;
  let offset = marker.length;
  if (value.startsWith(marker)) {
    value = value.slice(marker.length);
  }
  if (value.startsWith(' ')) {
    value = value.slice(1);
    offset += 1;
  }
  return { value, offset };
};

const stripBlockCommentLines = (lines, markerStart, markerEnd, stripStar) => {
  const trimmed = [];
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    let rawLine = line.raw;
    let offset = 0;
    if (i === 0 && rawLine.startsWith(markerStart)) {
      rawLine = rawLine.slice(markerStart.length);
      offset += markerStart.length;
    }
    if (i === lines.length - 1 && markerEnd && rawLine.endsWith(markerEnd)) {
      rawLine = rawLine.slice(0, -markerEnd.length);
    }
    const leading = rawLine.match(/^\s*/)?.[0]?.length || 0;
    rawLine = rawLine.slice(leading);
    offset += leading;
    if (stripStar && rawLine.startsWith('*')) {
      rawLine = rawLine.slice(1);
      offset += 1;
      if (rawLine.startsWith(' ')) {
        rawLine = rawLine.slice(1);
        offset += 1;
      }
    }
    trimmed.push({
      content: rawLine,
      contentStartOffset: line.offset + offset
    });
  }
  return trimmed;
};

const originalCommentType = (raw, kind, languageId) => {
  if (languageId === 'rust') {
    if (kind === 'line') return raw.startsWith('//!') || raw.startsWith('///') && !raw.startsWith('////') ? 'doc' : 'inline';
    return raw.startsWith('/*!') || raw.startsWith('/**') && !raw.startsWith('/***') && !raw.startsWith('/**/') ? 'doc' : 'block';
  }
  if (kind === 'block') {
    if (raw.startsWith('/**') || raw.startsWith('/*!') || raw.startsWith('<!--')) return 'doc';
  } else if (kind === 'line') {
    if (raw.startsWith('///') || raw.startsWith('//!') || raw.startsWith('##')) return 'doc';
  }
  return kind === 'line' ? 'inline' : 'block';
};

const classifyComment = (raw, kind, headerLine, config, languageId) => {
  const originalType = originalCommentType(raw, kind, languageId);
  if (!headerLine || !config.licensePattern) return { type: originalType, originalType, licenseClassification: null };
  const match = config.licensePattern.exec(raw);
  if (!match) return { type: originalType, originalType, licenseClassification: null };
  const builtIn = config.licensePattern.source === DEFAULT_COMMENT_LICENSE_PATTERN;
  return { type: 'license', originalType, licenseClassification: {
    policyVersion: COMMENT_CLASSIFICATION_VERSION, scope: 'comment-occurrence',
    reason: !builtIn ? 'configured-license-pattern' : match[1] ? 'spdx-notice'
      : match[2] ? 'copyright-notice' : 'license-notice',
    confidence: builtIn ? 'qualified-notice' : 'configured'
  } };
};

const hasEnoughChars = (text, minChars) => {
  if (!text) return false;
  const nonWhitespace = text.replace(/\s/g, '');
  return nonWhitespace.length >= minChars;
};

const shouldSkipNoise = (text, config) => {
  if (!text) return true;
  if (config.skipGenerated && config.generatedPattern?.test(text)) return true;
  if (config.skipLinter && config.linterPattern?.test(text)) return true;
  return false;
};

const scanComments = (text, style) => {
  const lineMarkers = style?.line || [];
  const blockMarkers = style?.block || [];
  const stringDelims = style?.strings || [];
  const out = [];
  let inString = null;
  let escaped = false;
  let i = 0;
  while (i < text.length) {
    const ch = text[i];
    if (inString) {
      if (escaped) {
        escaped = false;
      } else if (ch === '\\') {
        escaped = true;
      } else if (ch === inString) {
        inString = null;
      }
      i += 1;
      continue;
    }
    let matched = null;
    for (const block of blockMarkers) {
      if (text.startsWith(block.start, i)) {
        matched = { ...block, kind: 'block' };
        break;
      }
    }
    if (matched) {
      const start = i;
      const endIndex = text.indexOf(matched.end, i + matched.start.length);
      const end = endIndex === -1 ? text.length : endIndex + matched.end.length;
      out.push({
        start,
        end,
        raw: text.slice(start, end),
        kind: 'block',
        markerStart: matched.start,
        markerEnd: matched.end,
        stripStar: matched.stripStar === true
      });
      i = end;
      continue;
    }
    let lineMatch = null;
    for (const marker of lineMarkers) {
      if (text.startsWith(marker, i)) {
        lineMatch = marker;
        break;
      }
    }
    if (lineMatch) {
      const start = i;
      let end = text.indexOf('\n', i + lineMatch.length);
      if (end === -1) end = text.length;
      out.push({
        start,
        end,
        raw: text.slice(start, end),
        kind: 'line',
        markerStart: lineMatch,
        markerEnd: null,
        stripStar: false
      });
      i = end;
      continue;
    }
    if (stringDelims.includes(ch)) {
      inString = ch;
      i += 1;
      continue;
    }
    i += 1;
  }
  return out;
};

const hasPotentialCommentMarkers = (text, style) => {
  if (!text || !style) return false;
  const lineMarkers = Array.isArray(style.line) ? style.line : [];
  for (const marker of lineMarkers) {
    if (typeof marker === 'string' && marker && text.includes(marker)) return true;
  }
  const blockMarkers = Array.isArray(style.block) ? style.block : [];
  for (const block of blockMarkers) {
    const marker = typeof block?.start === 'string' ? block.start : '';
    if (marker && text.includes(marker)) return true;
  }
  return false;
};

export function extractComments({
  text,
  ext,
  languageId,
  lineIndex,
  config: rawConfig,
  context = null,
  commentOccurrences = null,
  includeConfigSegments = true,
  onConfigParse = null
}) {
  const config = normalizeCommentConfig(rawConfig || {});
  if (config.extract === 'off') {
    return { comments: [], configSegments: [] };
  }
  const style = resolveCommentStyle({ ext, languageId });
  if (!style) {
    return { comments: [], configSegments: [] };
  }
  if (!hasPotentialCommentMarkers(text, style)) {
    return { comments: [], configSegments: [] };
  }
  const comments = [];
  const configSegments = [];
  const configAdmission = createCommentConfigAdmission({ enabled: includeConfigSegments, onParse: onConfigParse });
  const resolved = resolveCommentOccurrences({ text, ext, languageId, context, commentOccurrences });
  if (['comment-count-budget', 'standalone-comment-parser-source-budget'].includes(resolved.reason) || resolved.reason?.startsWith('rust-comment-')) {
    return { comments, configSegments, coverage: { state: 'unavailable', reason: resolved.reason, policyVersion: 1 } };
  }
  const coverage = resolved.product?.complete ? { state: 'complete', reason: null,
    source: resolved.product.source, parser: resolved.product.parser, policyVersion: resolved.product.policyVersion }
    : { state: 'heuristic', reason: resolved.reason, policyVersion: 1 };
  const rawComments = resolved.product?.complete ? resolved.product.ranges.map(range => ({ ...range,
    raw: text.slice(range.start, range.end), markerStart: range.kind === 'line' ? '//' : '/*',
    markerEnd: range.kind === 'line' ? null : '*/', stripStar: range.kind === 'block' })) : scanComments(text, style);
  for (const entry of rawComments) {
    const startLine = offsetToLine(lineIndex, entry.start);
    const endLine = offsetToLine(lineIndex, Math.max(entry.start, entry.end - 1));
    const headerLine = Number.isFinite(config.headerMaxLines)
      ? startLine <= config.headerMaxLines
      : false;
    const commentLines = splitLinesWithOffsets(entry.raw, entry.start);
    let contentLines = [];
    if (entry.kind === 'line') {
      const stripped = stripLineComment(commentLines[0].raw, entry.markerStart);
      contentLines = [{
        content: stripped.value,
        contentStartOffset: commentLines[0].offset + stripped.offset
      }];
    } else {
      contentLines = stripBlockCommentLines(
        commentLines,
        entry.markerStart,
        entry.markerEnd,
        entry.stripStar
      );
    }
    const contentText = contentLines.map((line) => line.content).join('\n').trim();
    const classification = classifyComment(entry.raw, entry.kind, headerLine, config, languageId || EXT_OVERRIDES.get(ext));
    const commentType = classification.type;
    const minChars = commentType === 'doc' || commentType === 'license'
      ? config.minDocChars
      : config.minInlineChars;
    if (!hasEnoughChars(contentText, minChars)) continue;
    if (shouldSkipNoise(contentText, config)) continue;
    if (config.extract === 'doc' && commentType !== 'doc' && commentType !== 'license') {
      continue;
    }
    comments.push({
      ...classification,
      style: entry.kind,
      languageId: languageId || null,
      start: entry.start,
      end: entry.end,
      startLine,
      endLine,
      text: contentText,
      raw: entry.raw,
      coverage
    });
    if (!configAdmission.discover) continue;
    if (!/(?:`{3}|~{3})/u.test(entry.raw)) continue;
    const commentRange = { start: entry.start, end: entry.end };
    if (entry.end - entry.start > COMMENT_CONFIG_LIMITS.fileBytes) {
      configAdmission.unavailable('comment-content-byte-budget', commentRange); continue;
    }
    let scanned = true;
    for (let line = 0; line < commentLines.length; line++) {
      if (!configAdmission.scanLine(commentRange)) { scanned = false; break; }
    }
    if (!scanned) continue;
    let commentView, logicalComment;
    try {
      commentView = createCommentContentView(text, entry);
      logicalComment = readEmbeddedContent(text, commentView);
    } catch (error) {
      if (error.code !== 'ERR_EMBEDDED_CONTENT') throw error;
      configAdmission.unavailable(error.reason, commentRange); continue;
    }
    comments.at(-1).contentView = commentView;
    for (const block of collectMarkdownFencedContent(logicalComment)) {
      if (!configAdmission.discover) break;
      const fenceLang = (block.info || '').trim().split(/\s+/u)[0].toLowerCase();
      const lang = ['json', 'yaml', 'yml', 'toml'].includes(fenceLang) ? fenceLang : null;
      if (!lang) continue;
      if (!configAdmission.candidate(commentRange)) break;
      if (!block.closed) { configAdmission.unavailable('unclosed-comment-fence', commentRange); continue; }
      if (block.contentUnavailable || !block.contentView) {
        configAdmission.unavailable(block.contentUnavailable || 'content-unavailable', commentRange); continue;
      }
      let contentView, content;
      try {
        const pieces = block.contentView.pieces.flatMap(piece => mapEmbeddedContentRange(commentView, piece.start, piece.end));
        contentView = createEmbeddedContentView(text, pieces, { containerStart: entry.start, containerEnd: entry.end,
          policy: 'comment-config-fenced-content-v1' });
        content = readEmbeddedContent(text, contentView);
      } catch (error) {
        if (error.code !== 'ERR_EMBEDDED_CONTENT') throw error;
        configAdmission.unavailable(error.reason, commentRange); continue;
      }
      const startOffset = contentView.sourceStart, endOffset = contentView.sourceEnd;
      const normalizedLang = lang === 'yml' ? 'yaml' : lang;
      const admitted = configAdmission.parseContent(normalizedLang, content, { start: startOffset, end: endOffset });
      if (!admitted) continue;
      configSegments.push({
        type: 'embedded',
        languageId: normalizedLang,
        start: startOffset,
        end: endOffset,
        parentSegmentId: null,
        embeddingContext: 'config',
        contentView,
        meta: {
          fenceInfo: fenceLang || null,
          source: 'comment', containerStart: entry.start, containerEnd: entry.end,
          commentContentIdentity: embeddedContentIdentity(commentView),
          extractionPolicy: 'comment-config-fenced-content-v1'
        }
      });
    }
  }
  return { comments, configSegments, coverage, configAdmission: configAdmission.snapshot() };
}
