import assert from 'node:assert/strict';
import { createWorkerPoolLifecycle } from '../../../src/index/build/workers/pool/lifecycle.js';
import { IndexerProcessPool } from '../../../src/index/build/workers/process-pool.js';
let attempts = 0;
const owned = { destroy: async () => { if (++attempts === 1) throw new Error('termination unconfirmed'); } };
const lifecycle = createWorkerPoolLifecycle({ createPool: () => owned });
lifecycle.initialize();
await assert.rejects(lifecycle.forceDestroy(), /unconfirmed/);
assert.equal(lifecycle.getPool(), owned);
assert.throws(() => lifecycle.initialize(), /ownership/);
await lifecycle.forceDestroy();
assert.equal(lifecycle.getPool(), null);
let releases = 0, stopAttempts = 0;
const pool = new IndexerProcessPool({ budgetAccount: { reserve: () => () => { releases += 1; } } });
const slot = {}; pool.children.add(slot);
pool.stop = async () => { if (++stopAttempts === 1) throw new Error('unconfirmed'); pool.children.delete(slot); };
await assert.rejects(pool.destroy(), /unconfirmed/);
assert.equal(releases, 0, 'an unconfirmed live child retains its memory reservation');
await pool.destroy(); await pool.destroy();
assert.equal(releases, 1);
console.log('failed cleanup retains authority passed');
