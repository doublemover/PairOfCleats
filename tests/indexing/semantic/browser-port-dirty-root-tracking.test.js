import assert from 'node:assert/strict';
import ts from 'typescript';
import { createBrowserPortFlow } from '../../../src/index/semantic/compiler-browser-port-flow.js';
const sourceFile = ts.createSourceFile('ports.ts', 'event.data.port; other.data.port;', ts.ScriptTarget.Latest, true);
const symbols = { event: {}, other: {} };
const doc = { ts, checker: { getSymbolAtLocation: node => symbols[node.text] } };
const ledgers = new Map([[doc, { reasons: new Set() }]]);
const flow = createBrowserPortFlow({ documents: [doc], ledgers, platformType: () => false });
const first = sourceFile.statements[0].expression, second = sourceFile.statements[1].expression;
const observed = flow.capture(() => flow.read(doc, first));
assert.equal(observed.value, null); assert.equal(observed.dependencies.size, 1);
const channel = {}, ports = [{ channel, port: 'port2' }];
assert.equal(flow.bind(doc, symbols.event, ['data', 'port'], ports), true);
assert.deepEqual(flow.drainChangedRoots(), [...observed.dependencies]);
assert.deepEqual(flow.read(doc, first), { ports });
assert.equal(flow.bind(doc, symbols.event, ['data', 'port'], ports), false);
assert.deepEqual(flow.drainChangedRoots(), [], 'unchanged facts do not schedule another round');
const other = flow.capture(() => flow.read(doc, second));
assert.notEqual([...other.dependencies][0], [...observed.dependencies][0]);
flow.bind(doc, symbols.other, ['data', 'port'], [{ channel, port: 'port1' }]);
assert.deepEqual(flow.drainChangedRoots(), [...other.dependencies]);
console.log('received endpoint roots track misses, changes and independent dirty subscriptions');
