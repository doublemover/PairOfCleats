import assert from 'node:assert/strict';
import { buildCallSiteId } from '../../../src/index/callsite-id.js';
import { resolveShardSubsetId,createSeqLedger,STAGE1_SEQ_STATE } from '../../../src/index/build/indexer/steps/process-files/ordering.js';
import { resolveTreeSitterSchedulerPaths } from '../../../src/index/build/tree-sitter-scheduler/paths.js';
import { buildStageCheckpointModeBasename } from '../../../src/index/build/stage-checkpoints/sidecar.js';
import { mergeOrderingLedger } from '../../../src/index/build/build-state/order-ledger.js';
import { attachSegmentMeta } from '../../../src/index/segments/chunk-meta.js';
import { getFieldWeight } from '../../../src/index/field-weighting.js';
const first = {file:'a:1',startLine:2,startCol:3,endLine:4,endCol:5,calleeRaw:'f'};
const second = {file:'a',startLine:1,startCol:2,endLine:3,endCol:4,calleeRaw:'5:f'};
assert.notEqual(buildCallSiteId(first),buildCallSiteId(second)); assert.equal(buildCallSiteId(first),buildCallSiteId({...first}));
assert.notEqual(resolveShardSubsetId({shard:{id:'a/b'}}),resolveShardSubsetId({shard:{id:'a_b'}}));
const paths = resolveTreeSitterSchedulerPaths('task-owned-index');
assert.notEqual(paths.jobPathForGrammarKey('a/b'),paths.jobPathForGrammarKey('a_b'));
assert.notEqual(buildStageCheckpointModeBasename('alpha/beta'),buildStageCheckpointModeBasename('alpha?beta'));
assert.equal(mergeOrderingLedger({schemaVersion:2,stages:{s:{x:1}}},{stages:{s:{y:2}}}).schemaVersion,2);
const chunk = {start:0,end:5,meta:{startLine:2,endLine:3}};
const rebase = () => attachSegmentMeta({chunk,segmentStart:10,segmentEnd:20,segmentStartLine:10,segmentEndLine:20});
const a = rebase(),b = rebase();
assert.equal(chunk.meta.startLine,2); assert.equal(a.meta.startLine,11); assert.equal(b.meta.startLine,11);
assert.notEqual(a.meta,b.meta);
const ledger = createSeqLedger({expectedSeqs:[0]});
for (const state of [STAGE1_SEQ_STATE.DISPATCHED,STAGE1_SEQ_STATE.IN_FLIGHT,STAGE1_SEQ_STATE.TERMINAL_SUCCESS,STAGE1_SEQ_STATE.COMMITTED]) ledger.transition(0,state);
for (const key of ['terminalCount','committedCount','inFlightCount','dispatchedCount','nextCommitSeq']) assert.equal(ledger[key],ledger.snapshot()[key]);
assert.equal(getFieldWeight({kind:'FunctionDeclaration'},'src/contest.js'),2);
assert.equal(getFieldWeight({kind:'FunctionDeclaration'},'tests/app.test.js'),0.5);
console.log('structural identities, live ledgers and immutable segment rebasing passed');
