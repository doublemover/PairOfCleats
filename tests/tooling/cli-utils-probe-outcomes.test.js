import assert from 'node:assert/strict';
import path from 'node:path';
import { probeCommand } from '../../tools/shared/cli-utils.js';
import { prepareIsolatedTestCacheDir } from '../helpers/test-cache.js';
import { ensureTestingEnv } from '../helpers/test-env.js';

ensureTestingEnv(process.env);
const { dir } = await prepareIsolatedTestCacheDir('command-probe-outcomes');
const missing = probeCommand(path.join(dir, 'never-created-provider-command'), ['--version']);
assert.equal(missing.ok, false);
assert.equal(missing.outcome, 'missing', 'preserve the actual launch ENOENT instead of the generic subprocess wrapper code');
assert.equal(missing.errorCode, 'ENOENT');
assert.equal(missing.status, null);
const failed = probeCommand(process.execPath, ['-e', 'process.stderr.write("provider prerequisite unavailable\\n");process.exit(23)']);
assert.equal(failed.ok, false); assert.equal(failed.outcome, 'nonzero'); assert.equal(failed.status, 23);
assert.equal(failed.stderr, 'provider prerequisite unavailable\n', 'default probes retain the actual failed-executable diagnostic');
const successful = probeCommand(process.execPath, ['-e', 'process.stdout.write("fixture-provider 1.2.3\\n")']);
assert.equal(successful.ok, true); assert.equal(successful.status, 0);
assert.equal(successful.stdout, 'fixture-provider 1.2.3\n');
const bounded = probeCommand(process.execPath, ['-e', 'process.stderr.write("x".repeat(100000));process.exit(7)']);
assert.equal(bounded.outcome, 'nonzero'); assert.equal(bounded.status, 7);
assert.ok(bounded.stderr.length > 0 && bounded.stderr.length <= 16384, 'default diagnostic capture is bounded');
const explicitBuffer = probeCommand(process.execPath, ['-e', 'process.stdout.write("x".repeat(20000))'], { maxBuffer: 32768 });
assert.equal(explicitBuffer.stdout.length, 20000, 'an explicit legacy buffer cap still overrides the default');
const explicitCap = probeCommand(process.execPath, ['-e', 'process.stdout.write("x".repeat(20000))'], { maxOutputBytes: 1024 });
assert.equal(explicitCap.stdout.length, 1024, 'the canonical explicit cap remains authoritative');
const timedOut = probeCommand(process.execPath, ['-e', 'setInterval(()=>{},1000)'], { timeoutMs: 100 });
assert.equal(timedOut.ok, false); assert.equal(timedOut.outcome, 'timeout');
const ignored = probeCommand(process.execPath, ['-e', 'process.stderr.write("explicitly ignored");process.exit(9)'], { stdio: 'ignore' });
assert.equal(ignored.status, 9); assert.equal(ignored.stderr, '', 'explicit capture choices remain authoritative');
console.log('Command probes preserve launch causes, exit status, bounded diagnostics and real timeout outcomes');
