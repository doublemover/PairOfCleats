import assert from 'node:assert/strict';
import { ensureFixtureIndex } from '../../helpers/fixture-index.js';
import { applyTestEnv } from '../../helpers/test-env.js';
import { loadChunkMeta, loadJsonArrayArtifact } from '../../../src/shared/artifact-io.js';
import { buildRiskExplainPayload } from '../../../tools/analysis/explain-risk.js';
import { assembleCompositeContextPack } from '../../../src/context-pack/assemble.js';
import { projectOutput } from '../../../src/map/workspace/projection.js';
applyTestEnv();
const {fixtureRoot,codeDir}=await ensureFixtureIndex({fixtureName:'risk-interprocedural/js-simple',cacheName:'viewer-risk-producer',cacheScope:'isolated',requireRiskTags:true,requiredModes:['code']});
const chunkMeta=await loadChunkMeta(codeDir,{strict:true});
const summaries=await loadJsonArrayArtifact(codeDir,'risk_summaries',{strict:true});
assert.ok(summaries.length,'risk producer must emit summaries; do not silently skip');
const chunkUid=summaries[0].chunkUid;
const risk=await buildRiskExplainPayload({indexDir:codeDir,chunkUid,includePartialFlows:true});
const view=projectOutput(risk);assert.equal(view.family,'risk');
assert.strictEqual(view.sections.find(row=>row.title==='flows').value,risk.flows);
assert.strictEqual(view.sections.find(row=>row.title==='Complete original output').value,risk);
const pack=assembleCompositeContextPack({seed:{type:'chunk',chunkUid},chunkMeta,repoRoot:fixtureRoot,indexDir:codeDir,includeGraph:false,includeTypes:false,includeRisk:true,includeImports:false,includeUsages:false,includeCallersCallees:false,indexSignature:'fixture-risk'});
const packed=projectOutput(pack);assert.equal(packed.family,'context');
assert.strictEqual(packed.sections.find(row=>row.title==='risk').value,pack.risk);
assert.ok(pack.risk.analysisStatus);
console.log('Actual isolated risk-index producer → standalone explanation and composite risk context retain flows, partial paths, status and evidence.');
