import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { applyTestEnv } from '../../helpers/test-env.js';
import { buildIndex } from '../../../src/integrations/core/index.js';
import { getIndexDir, loadUserConfig } from '../../../tools/shared/dict-utils.js';
import { createArtifactBrowser } from '../../../src/map/workspace/catalog.js';
import { runSemanticDetail } from '../../../src/integrations/tooling/semantic-detail.js';
import { prepareGraphInputs, prepareGraphIndex } from '../../../src/integrations/tooling/graph-helpers.js';
import { buildGraphContextPack } from '../../../src/graph/context-pack.js';
import { buildImpactAnalysis } from '../../../src/graph/impact.js';
import { buildArchitectureReport } from '../../../src/graph/architecture.js';
import { buildSuggestTestsReport } from '../../../src/graph/suggest-tests.js';
import { assembleCompositeContextPack } from '../../../src/context-pack/assemble.js';
import { runSemanticEnrichmentService } from '../../../src/semantic/enrichment.js';
import { loadChunkMeta } from '../../../src/shared/artifact-io.js';
import { search } from '../../../src/integrations/core/search.js';
import { buildStackModel } from '../../../src/map/isometric/client/stack-model.js';
import { buildCodeMap } from '../../../src/map/build-map.js';
import { projectOutput } from '../../../src/map/workspace/projection.js';
import { authorProjection } from '../../../src/map/workspace/reladraw.js';
import { verifyMapIsoLauncher } from './launcher-fixture.js';
import { parse, resolve } from 'reladraw';
const temp=await fs.mkdtemp(path.join(os.tmpdir(),'poc-viewer-published-'));
const repo=path.join(temp,'repo');await fs.mkdir(repo);
await fs.writeFile(path.join(repo,'math.js'),'export function twice(value) { return value * 2; }');
await fs.writeFile(path.join(repo,'main.js'),'import { twice } from "./math.js"; export function run(input) { return twice(input); }');
applyTestEnv({cacheRoot:path.join(temp,'cache'),embeddings:'stub',testConfig:{indexing:{workerPool:{enabled:false},semantic:{enabled:true},embeddings:{enabled:false},typeInference:false,typeInferenceCrossFile:false,riskAnalysis:false,treeSitter:{enabled:false}}}});
const browser=createArtifactBrowser();
try {
  await buildIndex(repo,{mode:'code',stage:'stage2','stub-embeddings':true,'scm-provider':'none'});
  const catalog=await browser.catalog(repo);
  assert.ok(catalog.artifacts.find(row=>row.name==='semantic_records').available);
  const records=await browser.read(repo,{name:'semantic_records',generation:catalog.generation});
  assert.ok(records.rows.length);
  const selected=records.rows.find(row=>row.row.kind==='expression') || records.rows[0];
  assert.ok(selected.ref);assert.ok(selected.generation);
  const detail=await runSemanticDetail({repoRoot:repo,generation:selected.generation,refs:[selected.ref],include:['operands','names','ownership']});
  const projection=projectOutput(detail);assert.ok(projection.nodes.some(node=>node.ref.localId===selected.ref.localId));
  assert.ok(resolve(parse(authorProjection(projection).source)).nodes.length);
  const indexDir=getIndexDir(repo,'code',loadUserConfig(repo));
  const map=await buildCodeMap({repoRoot:repo,indexDir,options:{mode:'code'}});
  const stacks=buildStackModel(map.nodes,map.edges);assert.equal(stacks.files.length,map.nodes.length);assert.equal(stacks.files.reduce((sum,file)=>sum+file.members.length,0),map.nodes.reduce((sum,file)=>sum+file.members.length,0));
  assert.ok(map.nodes.length>=2);const mapped=projectOutput(map);assert.ok(mapped.nodes.length>=2);
  assert.equal(resolve(parse(authorProjection(mapped).source)).nodes.length,mapped.nodes.length);
  const graphInputs=await prepareGraphInputs({repoRoot:repo,indexDir,strict:true});
  const {graphIndex,graphRelations}=await prepareGraphIndex({repoRoot:repo,indexDir,graphInputs,includeGraphRelations:true});
  const args={seed:{type:'file',path:'main.js'},graphIndex,indexSignature:graphInputs.indexSignature,depth:1,caps:{maxNodes:20,maxEdges:20,maxWorkUnits:1000}};
  const graph=buildGraphContextPack({...args,direction:'out',includePaths:true});
  assert.equal(projectOutput(graph).family,'graph');assert.ok(graph.nodes.length);
  const impact=buildImpactAnalysis({...args,direction:'downstream'});assert.equal(projectOutput(impact).family,'impact');
  const architecture=buildArchitectureReport({rules:{version:1,rules:[{id:'no-math',type:'forbiddenImport',from:{anyOf:['main.js']},to:{anyOf:['math.js']}}]},graphRelations,repoRoot:repo,indexSignature:graphInputs.indexSignature});
  const archView=projectOutput(architecture);assert.equal(archView.family,'architecture');
  assert.ok(architecture.violations.length);assert.strictEqual(archView.nodes[0].detail,architecture.violations[0]);
  const suggestions=buildSuggestTestsReport({changed:['math.js'],tests:['tests/math.test.js'],graphRelations,repoRoot:repo,indexSignature:graphInputs.indexSignature});
  const testView=projectOutput(suggestions);assert.equal(testView.family,'tests');assert.ok(testView.nodes.length);
  assert.strictEqual(testView.nodes[0].detail.fidelity,suggestions.suggestions[0].fidelity);
  const chunkMeta=await loadChunkMeta(indexDir,{strict:true});
  const context=assembleCompositeContextPack({seed:{type:'chunk',chunkUid:chunkMeta[0].chunkUid},chunkMeta,repoRoot:repo,indexDir,includeGraph:false,includeTypes:false,includeRisk:false,indexSignature:graphInputs.indexSignature});
  const contextView=projectOutput(context);assert.equal(contextView.family,'context');
  assert.strictEqual(contextView.sections.find(row=>row.title==='Primary source and exact range').value,context.primary);
  const plan=await runSemanticEnrichmentService({request:{schemaVersion:1,repoRoot:repo,generation:selected.generation,limits:{maxTasks:32,maxBytes:65536,maxMs:1000,drainMaxMs:1000}}});
  const enrichmentView=projectOutput(plan);assert.equal(enrichmentView.family,'enrichment');
  assert.equal(plan.executionAuthorized,false);assert.equal(enrichmentView.nodes.length,plan.tasks.length);
  const found=await search(repo,{args:['--backend','memory','--mode','code','--json','--no-ann'],query:'twice',emitOutput:false,exitOnError:false});
  const ranked=projectOutput(found);assert.equal(ranked.family,'search');assert.ok(ranked.nodes.length);
  assert.equal(ranked.nodes[0].detail.originalRank,1);
  await verifyMapIsoLauncher(repo,temp);
  console.log('Real two-file published index → catalog → semantic rows → detail → Reladraw, plus real code-map producer projection passed.');
} finally {await browser.close();await fs.rm(temp,{recursive:true,force:true});}
