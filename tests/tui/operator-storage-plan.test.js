import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { prepareTuiStorage } from '../../tools/tui/operator/storage.js';
import { resolveStorageLayout } from '../../src/shared/storage/layout.js';
import { CACHE_OWNER_FILE } from '../../src/shared/cache-deletion.js';
import { withGeneratedCacheMetadata } from '../../src/shared/generated-artifact-cache.js';
import { prepareIsolatedTestCacheDir } from '../helpers/test-cache.js';
import { applyTestEnv } from '../helpers/test-env.js';

const { dir } = await prepareIsolatedTestCacheDir('native-storage-plan');
const env = applyTestEnv({ cacheRoot: path.join(dir, 'cache'),
  extraEnv: { PAIROFCLEATS_HOME: path.join(dir, 'home') } });
const layout = resolveStorageLayout({ env }), root = layout.descriptors.cache.path;
const probe = path.join(root, 'tooling/command-probes', `${'b'.repeat(40)}.json`);
await fs.mkdir(path.dirname(probe), { recursive: true });
await fs.writeFile(path.join(root, CACHE_OWNER_FILE), JSON.stringify({ owner: 'pairofcleats', layoutVersion: 1 }));
await fs.writeFile(probe, JSON.stringify(withGeneratedCacheMetadata({ result: 'disposable' }, 'command-probe')));
const scope = { id: 'selected', configRoot: dir };
const input = { commandId: 'storage.cleanup-apply', scope, env, values: {}, requireScope: () => scope };
const reviewed = await prepareTuiStorage(input);
assert.equal(reviewed.review.launchable, true);
assert.equal(reviewed.review.canonicalPlan.operations.length, 1);
assert.equal(reviewed.review.approvedPlanId, reviewed.review.canonicalPlan.planId);
reviewed.review.canonicalPlan.operations.length = 0;
const result = JSON.parse((await reviewed.execute({})).stdout);
assert.equal(result.results.length, 1, 'public projection mutation cannot replace the retained exact plan');
assert.equal(result.results[0].status, 'deleted');
assert.equal(result.actualReclaimedBytes, null);
await fs.writeFile(probe, JSON.stringify(withGeneratedCacheMetadata({ result: 'new' }, 'command-probe')));
const changed = await prepareTuiStorage(input);
await fs.writeFile(probe, JSON.stringify(withGeneratedCacheMetadata({ result: 'replacement' }, 'command-probe')));
const rejected = JSON.parse((await changed.execute({})).stdout);
assert.equal(rejected.results[0].status, 'failed');
assert.match(await fs.readFile(probe, 'utf8'), /replacement/);
const stale = await prepareTuiStorage(input);
env.PAIROFCLEATS_HOME = path.join(dir, 'different-home');
await assert.rejects(stale.execute({}), { code: 'ERR_TUI_STORAGE_STALE' });
console.log('Native storage retains canonical exact plan identity and rejects replacement/root drift');
